BT_MACRO = """        bt_{n}: bt_profile_macro_{n} {{
            label = "BT_{n}";
            compatible = "zmk,behavior-macro";
            #binding-cells = <0>;
            bindings = <&out OUT_BLE>, <&bt BT_SEL {n}>;
        }};
"""

MORPH = """        pos_{i}: pos_{i} {{
            compatible = "zmk,behavior-mod-morph";
            label = "POS_{i}";
            #binding-cells = <0>;
            bindings = <{plain}>, <&kp {factory}>;
            mods = <{mods}>;
            keep-mods = <{mods}>;
        }};
"""

UNSHIFT = """        sh_{kc}: sh_{kc} {{
            compatible = "zmk,behavior-mod-morph";
            label = "SH_{kc}";
            #binding-cells = <0>;
            bindings = <&kp {kc}>, <&kp {kc}>;
            mods = <(MOD_LSFT|MOD_RSFT)>;
        }};
"""


def parse(text):
    layers, name = {}, None
    for line in text.splitlines():
        if line.endswith(":"):
            name = line[:-1]
            layers[name] = []
        elif name and line.strip() and len(layers[name]) < 4:
            layers[name].append(line.split())
    return layers


def binding(token):
    if token not in KC:
        return "&none"
    return f"&sh_{KC[token]}" if KC[token] in SHIFTABLE else f"&kp {KC[token]}"


def keymap(text, source="a layout file"):
    layers = parse(text)
    morphs, base_rows, sym_rows = [], [], []
    for r in range(4):
        row = []
        for c, token in enumerate(layers["base"][r]):
            i = 10 + 12 * r + c + (6 if r == 3 and c >= 6 else 0)
            plain, factory = binding(token), FACTORY[r][c]
            if plain in (f"&kp {factory}", f"&sh_{factory}"):
                row.append(plain)
            else:
                morphs.append(MORPH.format(i=i, plain=plain, factory=factory, mods=POSITIONAL))
                row.append(f"&pos_{i}")
        base_rows.append(row)
        sym_rows.append([binding(t) for t in layers["sym"][r]])

    def body(rows, row1, thumbs_upper, row6):
        lines = [row1] + [" ".join(r) for r in rows[:3]]
        lines.append(" ".join(rows[3][:6] + [thumbs_upper] + rows[3][6:]))
        lines.append(row6)
        return "\n".join("            " + l for l in lines)

    base = body(base_rows, BASE_ROW1, UPPER_THUMBS, f"{BASE_ROW6_LEFT} {LOWER_THUMBS} {BASE_ROW6_RIGHT}")
    sym = body(sym_rows, SYM_ROW1, TRANS6, SYM_ROW6)
    used = sorted({b[4:] for row in base_rows + sym_rows for b in row if b.startswith("&sh_")} |
                  {m.split("<&sh_")[1].split(">")[0] for m in morphs if "<&sh_" in m})
    morphs = [UNSHIFT.format(kc=kc) for kc in used] + morphs
    return TEMPLATE.format(source=source, morphs="".join(morphs), base=base, sym=sym,
                           bt_macros="".join(BT_MACRO.format(n=n) for n in range(4)))


if __name__ == "__main__":
    sys.stdout.write(keymap(open(sys.argv[1]).read(), sys.argv[1]))
