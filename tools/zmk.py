"""Turn a layout file into a Glove80 ZMK keymap.

Usage: python3 tools/zmk.py LAYOUT > glove80.keymap
Keys whose character differs from the factory key send the factory key while Ctrl or Meta is held,
so shortcuts stay where QWERTY put them.
"""
import sys

KC = {c: c.upper() for c in "abcdefghijklmnopqrstuvwxyz"} | {d: f"N{d}" for d in "0123456789"} | {
    "!": "EXCL", '"': "DQT", "#": "HASH", "$": "DLLR", "%": "PRCNT", "&": "AMPS", "'": "SQT",
    "(": "LPAR", ")": "RPAR", "*": "STAR", "+": "PLUS", ",": "COMMA", "-": "MINUS", ".": "DOT",
    "/": "FSLH", ":": "COLON", ";": "SEMI", "<": "LT", "=": "EQUAL", ">": "GT", "?": "QMARK",
    "@": "AT", "[": "LBKT", "\\": "BSLH", "]": "RBKT", "^": "CARET", "_": "UNDER", "`": "GRAVE",
    "{": "LBRC", "|": "PIPE", "}": "RBRC", "~": "TILDE", "⇥": "TAB", "⎋": "ESC",
}

FACTORY = [
    "EQUAL N1 N2 N3 N4 N5 N6 N7 N8 N9 N0 MINUS",
    "TAB Q W E R T Y U I O P BSLH",
    "ESC A S D F G H J K L SEMI SQT",
    "GRAVE Z X C V B N M COMMA DOT FSLH PG_UP",
]
FACTORY = [row.split() for row in FACTORY]

BASE_ROW1 = "&kp F1 &kp F2 &kp F3 &kp F4 &kp F5 &kp F6 &kp F7 &kp F8 &kp F9 &kp F10"
UPPER_THUMBS = "&kp LSHFT &kp LCTRL &mo SYM &mo SYM &kp RCTRL &kp RSHFT"
BASE_ROW6_LEFT = "&magic MAGIC 0 &kp HOME &kp END &kp LEFT &kp RIGHT"
LOWER_THUMBS = "&kp BSPC &kp DEL &kp LGUI &kp RGUI &kp RET &kp SPACE"
BASE_ROW6_RIGHT = "&kp UP &kp DOWN &kp LBKT &kp RBKT &kp PG_DN"
SYM_ROW1 = "&kp C_BRI_DN &kp C_BRI_UP &kp C_PREV &kp C_NEXT &kp C_PP &kp C_MUTE &kp C_VOL_DN &kp C_VOL_UP &none &kp PAUSE_BREAK"
SYM_ROW6 = "&trans &kp CAPS &kp INS &kp F11 &kp F12 " + " ".join(["&trans"] * 11)
TRANS6 = " ".join(["&trans"] * 6)

POSITIONAL = "(MOD_LCTL|MOD_RCTL|MOD_LGUI|MOD_RGUI)"
# Keycodes that Shift would turn into another character; on this board Shift only capitalizes.
SHIFTABLE = {KC[c] for c in "1234567890-=[]\\;',./`"}

